'use strict';

// Synthetic books exercise real query, renderer and portable-state paths. No
// live installation or user library is opened by this regression.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('./playwright-runtime.cjs');
const { createFixtures, createFakeModel, attachFakeIpc, launchOptions, appURL } = require('./test-gallery.cjs');
const { validateClientState } = require('../resources/app/modules/client_state');
const output = path.join(__dirname, '.artifacts', 'smart-shelves');
const checks = [];
const pass = name => { checks.push(name); console.log('PASS ' + name); };

(async () => {
  const { LibraryIndex, tagKey } = await import(pathToFileURL(path.join(__dirname,'../resources/app/dist/room-library.js')));
  const { normalizeShelfQuery, normalizeLibraryState, normalizeSmartShelves, shelfMatches } = await import(pathToFileURL(path.join(__dirname,'../resources/app/dist/room-shelves.js')));
  const a = {id:'a',hash:'hash-a',title:'Atlas',tags:{artist:['甲'],other:['彩色']},mark:true};
  const b = {id:'b',hash:'hash-b',title:'Atlas B',tags:{artist:['甲'],other:['灰度']},mark:true};
  const c = {id:'c',hash:'hash-c',title:'Atlas C',tags:{artist:['乙']}};
  const hidden = {...a,id:'hidden',hiddenBook:true};
  const collections=[{id:'legacy',title:'合集',list:['hash-a','b','hidden','missing']}];
  let index=new LibraryIndex([a,b,c,hidden],collections);
  const query=normalizeShelfQuery({search:'Atlas',selectedTags:[tagKey('artist','甲')],excludedTags:[tagKey('other','彩色')],favorites:true,collectionId:'legacy'});
  assert.deepEqual(index.select(query).map(book=>book.id),['b']);
  assert.equal(index.collections.get('legacy').ids.size,2);
  pass('search, inclusion, exclusion, favorites and legacy ID/hash collections combine without exposing hidden books');
  const shelf={id:'saved',name:'灰度待读',query:normalizeShelfQuery({...query,collectionId:''})};
  index=new LibraryIndex([a,b,c,{...b,id:'new',hash:'new'}]);
  assert.deepEqual(index.select(shelf.query).map(book=>book.id),['b','new']);
  assert(shelfMatches(shelf,shelf.query));
  const future=normalizeShelfQuery({selectedTags:[tagKey('artist','未来作者')]});
  assert.equal(new LibraryIndex([a,b]).select(future).length,0);
  assert.equal(new LibraryIndex([a,b,{id:'future',tags:{artist:['未来作者']}}]).select(future).length,1);
  assert.equal(new LibraryIndex([a]).select({collectionId:'removed'}).length,0);
  pass('saved queries include future matches and retain absent-tag or missing-collection criteria');
  assert.deepEqual(normalizeSmartShelves([{id:'bad',name:' ',query:{}},{id:'valid',name:'有效',query:{}},{id:'valid',name:'重复',query:{}}]).map(s=>s.name),['有效']);
  assert.equal(normalizeLibraryState({page:-8,density:'broken'}).page,1);
  const savedState=normalizeLibraryState({...query,view:'grid',density:'compact',page:4,scrollTop:450});
  const portable={schemaVersion:1,values:{'room-library-state':JSON.stringify(savedState),'room-smart-shelves':JSON.stringify([shelf]),'room-quality':'"power"'}};
  assert.deepEqual(validateClientState(portable).values, Object.assign(Object.create(null),portable.values));
  assert.throws(()=>validateClientState({schemaVersion:1,values:{'room-smart-shelves':JSON.stringify([{...shelf,query:{...query,selectedTags:['invalid']}}])}}));
  assert.throws(()=>validateClientState({schemaVersion:1,values:{'room-quality':'"unknown"'}}));
  pass('portable backup accepts shelf rules and rejects malformed tags or quality values');

  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'yanruyu-smart-shelves-'));
  let browser;
  const diagnostics=[];
  try {
    await fs.mkdir(output,{recursive:true});
    const fixture=createFixtures(directory,73,5);
    fixture.books.forEach((book,i)=>{book.hash='fixture-hash-'+i;book.tags.other=['静物',i%4===0?'彩色':'灰度'];book.hiddenBook=i===72;});
    const model=createFakeModel(fixture.books,fixture.pages);
    model.collections=[{id:'legacy-fixture',title:'原有合集',list:['fixture-hash-0',fixture.books[1].id,fixture.books[72].id,'missing']}];
    Object.assign(model.setting,{pageSize:42,theme:'light e-hentai',viewerType:'original',directEnter:'internalViewer',keepReadingProgress:true,language:'zh-CN',loadOnStart:false,defaultExpandTree:false,autoCheckUpdates:false,keyMap:{},titleBar:'default',enableLANBrowsing:false});
    const invoke=model.invoke.bind(model);
    model.invoke=async(channel,...args)=>{
      if(channel==='get-locale')return 'zh-CN';
      if(channel==='get-folder-tree')return [];
      if(channel==='window-is-maximized')return false;
      if(['set-progress-bar','update-tag-translation'].includes(channel))return null;
      if(channel==='save-ui-state')validateClientState(args[0]);
      return invoke(channel,...args);
    };
    browser=await chromium.launch(launchOptions());
    const context=await browser.newContext({viewport:{width:1440,height:1000}});
    await context.route(/^https?:/,route=>route.abort());
    await attachFakeIpc(context,model);
    await context.addInitScript(()=>{
      window.ipcRenderer.sendSync=()=> '\\';
      window.electronFunction={'get-zoom-level':()=>0,'set-zoom-level':()=>{},'insert-css':()=>{}};
    });
    const page=await context.newPage();
    page.on('pageerror',error=>diagnostics.push(error.message));
    await page.goto(appURL);await page.locator('#room [data-book]').first().waitFor();
    await page.fill('#tag-search','作者');await page.selectOption('#tag-group','artist');
    await page.evaluate(()=>window.YanruyuClientState.flush());
    const captured=JSON.parse(model.uiState.values['room-library-state']);
    assert.equal(captured.tagSearch,'作者');assert.equal(captured.tagGroup,'artist');
    await page.fill('#tag-search','');await page.selectOption('#tag-group','');
    pass('an immediate portable snapshot captures current tag search and group before delayed UI saves');
    await page.locator('[data-view="grid"]').click();
    await page.selectOption('#grid-density','standard');
    await page.waitForFunction(()=>document.querySelectorAll('#room [data-book]').length===24);
    await page.fill('#shelf-page','3');await page.locator('#shelf-jump button').click();
    await page.waitForFunction(()=>document.querySelector('#pagination')?.textContent==='03 / 03');
    const thirdPage=await page.locator('#room [data-book]').evaluateAll(nodes=>nodes.map(node=>node.dataset.book));
    await page.locator('.content').evaluate(element=>element.scrollTo(0,180));
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('room-library-state'))?.scrollTop>100);
    const scrollTop=await page.locator('.content').evaluate(element=>element.scrollTop);
    assert(scrollTop>100,'The independent library viewport must actually scroll before testing restoration');
    await page.reload();await page.waitForFunction(()=>document.querySelector('#pagination')?.textContent==='03 / 03');
    await page.waitForFunction(expected=>Math.abs(document.querySelector('.content').scrollTop-expected)<2,scrollTop);
    assert.deepEqual(await page.locator('#room [data-book]').evaluateAll(nodes=>nodes.map(node=>node.dataset.book)),thirdPage);
    assert.equal(await page.inputValue('#grid-density'),'standard');
    pass('density and direct shelf-page navigation survive renderer reload with the same books');
    await page.locator('[data-action="classic"]').first().click();
    await page.getByRole('button',{name:'返回 3D 阅览室',exact:true}).waitFor();
    await page.waitForFunction(()=>document.documentElement.classList.contains('manager-interface'));
    await page.getByRole('button',{name:'返回 3D 阅览室',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#pagination')?.textContent==='03 / 03');
    await page.waitForFunction(expected=>Math.abs(document.querySelector('.content').scrollTop-expected)<2,scrollTop);
    assert.deepEqual(await page.locator('#room [data-book]').evaluateAll(nodes=>nodes.map(node=>node.dataset.book)),thirdPage);
    pass('the actual classic manager round trip preserves shelf page and grid density');
    await page.selectOption('#collection-select','legacy-fixture');
    await page.waitForFunction(()=>document.querySelectorAll('#room [data-book]').length===2);
    assert.match(await page.textContent('#results'),/共 2 本/);
    await page.locator('#reset-filters').click();
    await page.fill('#search','静物');
    await page.locator('#tag-list [data-tag-key]').filter({hasText:'作者甲'}).click();
    await page.getByRole('button',{name:'排除标签 彩色',exact:true}).click();
    await page.locator('[data-filter="unread"]').click();
    await page.waitForFunction(()=>document.querySelector('#results')?.textContent.includes('共 18 本'));
    await page.locator('[data-action="save-shelf"]').click();await page.fill('#shelf-name','静物待读');
    await page.locator('#shelf-editor button[type="submit"]').click();
    const shelfId=await page.inputValue('#smart-shelf');assert(shelfId);
    model.books.push({...fixture.books[2],id:'new-matching-book',hash:'new-fixture-hash',title:'静物新档案',createdAt:new Date().toISOString()});
    await page.reload();await page.waitForFunction(()=>document.querySelector('#results')?.textContent.includes('共 19 本'));
    assert.equal(await page.inputValue('#smart-shelf'),shelfId);
    assert(await page.locator('#room [data-book="new-matching-book"]').count());
    pass('saved include/exclude rules automatically show a newly added matching book after restart');
    await page.locator('[data-action="manage-shelves"]').click();
    await page.locator('[data-shelf-rename]').click();await page.fill('#shelf-name','改名后的待读书架');
    await page.locator('#shelf-editor button[type="submit"]').click();
    assert.match(await page.locator('#smart-shelf option:checked').textContent(),/改名后的/);
    await page.locator('#reset-filters').click();await page.selectOption('#smart-shelf',shelfId);
    await page.waitForFunction(()=>document.querySelector('#results')?.textContent.includes('共 19 本'));
    pass('shelves can be renamed and reopened with their original rules');
    const editedId='new-matching-book',beforeConcurrent=model.invoke;
    model.invoke=async(channel,...args)=>{
      if(channel==='save-book'&&args[0].id===editedId)model.books.find(book=>book.id===editedId).title='静物 · 最新元数据';
      return beforeConcurrent(channel,...args);
    };
    await page.locator('#room [data-book="new-matching-book"]').click();await page.locator('.drawer').waitFor();
    await page.locator('[data-favorite]').click();
    await page.waitForFunction(()=>document.querySelector('[data-favorite]')?.getAttribute('aria-pressed')==='true');
    assert.equal(model.books.find(book=>book.id===editedId).title,'静物 · 最新元数据');
    assert(model.calls.some(call=>call.channel==='save-book'&&call.args[0].id===editedId&&Object.keys(call.args[0]).length===2));
    await page.keyboard.press('Escape');
    pass('a favorite edit sends only changed fields and preserves metadata updated during the request');
    await page.locator('[data-action="settings"]').click();await page.selectOption('#setting-quality','power');
    await page.selectOption('#cache-budget','4294967296');
    await page.waitForFunction(()=>document.querySelector('#cache-status')?.textContent.includes('4.0 GB'));
    await page.locator('[data-action="clear-cache"]').click();
    await page.keyboard.press('Escape');
    assert(model.calls.some(call=>call.channel==='image-cache-clear'));
    await page.evaluate(()=>window.YanruyuClientState.flush());
    const portableState=JSON.parse(JSON.stringify(model.uiState));
    assert.equal(portableState.values['room-quality'],'"power"');
    pass('quality and cache controls use the desktop contracts and preserve portable preferences');
    await page.screenshot({path:path.join(output,'smart-shelves-wide.png'),fullPage:true});
    await page.setViewportSize({width:520,height:850});
    await page.screenshot({path:path.join(output,'smart-shelves-narrow.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    pass('combined library controls fit a narrow window without horizontal overflow');
    await context.close();
    model.uiState=portableState;
    const restored=await browser.newContext({viewport:{width:1200,height:900}});
    await attachFakeIpc(restored,model);
    const restoredPage=await restored.newPage();
    await restoredPage.goto(appURL);await restoredPage.waitForFunction(()=>document.querySelector('#results')?.textContent.includes('共 19 本'));
    assert.equal(await restoredPage.inputValue('#smart-shelf'),shelfId);
    assert.equal(await restoredPage.evaluate(()=>JSON.parse(localStorage.getItem('room-quality'))),'power');
    pass('a fresh browser profile restores smart shelves, filters and quality from portable UI state');
    await restored.close();
    const tags=Array.from({length:201},(_,i)=>'tag-'+String(i).padStart(3,'0'));
    const limitModel=createFakeModel([
      {...fixture.books[0],id:'all201',title:'All tags',hiddenBook:false,tags:{other:tags}},
      {...fixture.books[0],id:'first200',title:'First 200',hiddenBook:false,tags:{other:tags.slice(0,200)}}
    ],fixture.pages);
    const limitContext=await browser.newContext({viewport:{width:1200,height:900}});
    await attachFakeIpc(limitContext,limitModel);
    const limitState=normalizeLibraryState({view:'grid',selectedTags:tags.slice(0,200).map(tag=>tagKey('other',tag))});
    await limitContext.addInitScript(value=>{if(!localStorage.getItem('room-library-state'))localStorage.setItem('room-library-state',JSON.stringify(value));},limitState);
    const limitPage=await limitContext.newPage();await limitPage.goto(appURL);
    await limitPage.waitForFunction(()=>document.querySelectorAll('#room [data-book]').length===2);
    await limitPage.fill('#tag-search','tag-200');await limitPage.locator('#tag-list .tag-filter').click();
    await limitPage.waitForFunction(()=>document.querySelector('#toast')?.textContent.includes('200 个标签'));
    assert.equal(await limitPage.locator('#room [data-book]').count(),2);
    assert.equal(await limitPage.evaluate(()=>JSON.parse(localStorage.getItem('room-library-state')).selectedTags.length),200);
    await limitPage.reload();await limitPage.waitForFunction(()=>document.querySelectorAll('#room [data-book]').length===2);
    await limitContext.close();
    pass('the 201st tag is explicitly refused so restart cannot silently broaden the saved query');
    assert.deepEqual(diagnostics,[]);
    pass('smart-shelf workflows finish without renderer exceptions');
  } finally {
    await browser?.close();
    await fs.mkdir(output,{recursive:true});
    await fs.writeFile(path.join(output,'checks.json'),JSON.stringify({checks,diagnostics},null,2));
    const resolved=path.resolve(directory),temporaryRoot=path.resolve(os.tmpdir());
    if(path.dirname(resolved)!==temporaryRoot||!path.basename(resolved).startsWith('yanruyu-smart-shelves-'))throw Error('Refusing cleanup outside the isolated fixture');
    await fs.rm(resolved,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
